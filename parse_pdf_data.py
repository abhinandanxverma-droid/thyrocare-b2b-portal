    clean_lines = []
    category = "PACKAGES"
    
    lines = raw_ocr_pages.split('\n')
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if not line:
            continue
        if line.startswith('===PAGE'):
            continue
        if line in ['PACKAGES', 'PROFILE', 'TESTS', 'OUTLAB TESTS']:
            category = line
            continue
        # If line consists mostly of table header keywords, skip it
        lower_line = line.lower()
        if any(h in lower_line for h in ['test code', 'test name', 'your rate', 'offer mrp', 'b2b (rs.)']):
            continue
        if line in ['Sr', 'No', 'Test Code', 'Test', 'Code', 'Test Name', 'Your', 'Rate', 'MRP', 'Your Rate']:
            continue
        clean_lines.append((category, line))

    sr_regex = re.compile(r'^(\d+)\s+([A-Za-z0-9_\-\.]+)\s+(.*)$')
    
    all_raw_items = []
    buffer = ""
    current_cat = "PACKAGES"

    idx = 0
    while idx < len(clean_lines):
        cat, line = clean_lines[idx]
        idx += 1
        
        # Check if line starts a new record (digit followed by code)
        m = sr_regex.match(line)
        if m:
            if buffer:
                all_raw_items.append((current_cat, buffer))
            buffer = line
            current_cat = cat
        else:
            # continuation of previous line
            buffer += " " + line
            
    if buffer:
        all_raw_items.append((current_cat, buffer))

    print(f"Total raw items grouped: {len(all_raw_items)}")

    parsed_tests = []
    seen_codes = set()

    for cat, item_str in all_raw_items:
        item_str = re.sub(r'\s+', ' ', item_str).strip()
        
        # Look for the last pair of numbers in item_str
        # Usually it ends with <rate> <mrp>, or <rate> <mrp> followed by trailing text if OCR wrapped
        num_matches = list(re.finditer(r'\b(\d+)\s+(\d+)\b', item_str))
        if not num_matches:
            print(f"FAILED TO MATCH RATES: {item_str}")
            continue
        
        # Take the last pair of numbers
        last_num = num_matches[-1]
        rate = int(last_num.group(1))
        mrp = int(last_num.group(2))
        
        # Text before and text after the numbers
        prefix = item_str[:last_num.start()].strip()
        suffix = item_str[last_num.end():].strip()
        
        # sr_no is at start of prefix
        sr_m = re.match(r'^(\d+)\s+(.*)$', prefix)
        if not sr_m:
            print(f"FAILED TO MATCH SR NO: {item_str}")
            continue
            
        sr_no = int(sr_m.group(1))
        rest = sr_m.group(2).strip()
        if suffix:
            rest += " " + suffix

        
        # Split rest into code and name
        # Usually code is the first token. Special cases: "AA XWU", "AA XLWU", "CARD MARK", "DOA P6", "Q -TB", "HBA P"
        special_multi_word_codes = {
            "AA XWU": "AA XWU",
            "AA XLWU": "AA XLWU",
            "CARD MARK": "CARD MARK",
            "DOA P6": "DOA P6",
            "Q -TB": "Q-TB",
            "HBA P": "HBA P",
            "BONE B": "BONE B",
            "HEP B": "HEP B",
            "HEP TOT": "HEP TOT"
        }
        
        matched_special = False
        code = None
        name = None
        for sm, canon in special_multi_word_codes.items():
            if rest.startswith(sm + " "):
                code = canon
                name = rest[len(sm):].strip()
                matched_special = True
                break
                
        if not matched_special:
            parts = rest.split(' ', 1)
            code = parts[0].strip()
            name = parts[1].strip() if len(parts) > 1 else code

        # Specimen inference
        specimen = "Blood / Serum"
        u_name = name.upper()
        if "URINE" in u_name or "STOOL" in u_name:
            specimen = "Urine / Stool"
        elif "CSF" in u_name or "FLUID" in u_name or "CYTOLOGY" in u_name or "PLEURAL" in u_name or "ASCITIC" in u_name:
            specimen = "Fluid / Effusion"
        elif "ALLERGY" in u_name:
            specimen = "Serum (Allergy)"
        elif "BIOPSY" in u_name or "TISSUE" in u_name or "HISTO" in u_name or "FNAC" in u_name or "SMEAR" in u_name:
            specimen = "Tissue / Biopsy"
        elif "BUCCAL" in u_name or "SWAB" in u_name:
            specimen = "Swab / Epithelial"
        elif "CULTURE" in u_name:
            specimen = "Microbiology Specimen"

        margin = mrp - rate
        margin_pct = round((margin / mrp) * 100, 1) if mrp > 0 else 0.0

        item_obj = {
            "code": code,
            "name": name,
            "category": cat.title(),
            "specimen": specimen,
            "b2b_rate": rate,
            "mrp": mrp,
            "margin": margin,
            "margin_pct": margin_pct,
            "description": f"Official Thyrocare {cat.title()}: {name}."
        }
        parsed_tests.append(item_obj)

    print(f"Successfully parsed {len(parsed_tests)} diagnostic tests.")

